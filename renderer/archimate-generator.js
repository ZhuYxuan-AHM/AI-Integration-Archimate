/*
 * archimate-generator.js
 * Generates a valid ArchiMate 3.2 XML (.archimate) file from the in-memory model.
 * Output can be opened directly in Archi tool for visualization.
 */

const ArchiMateGenerator = {

  // ArchiMate element type strings (as used in Archi .archimate XML)
  TYPE_MAP: {
    "ai-app":      "archimate:ApplicationComponent",
    "ai-model":    "archimate:DataObject",
    "assessment":  "archimate:Assessment",
    "role":        "archimate:BusinessRole",
    "actor":       "archimate:BusinessActor",
    "process":     "archimate:BusinessProcess",
    "function":    "archimate:BusinessFunction",
    "constraint":  "archimate:Constraint",
    "stakeholder": "archimate:Stakeholder",
    "driver":      "archimate:Driver",
    "goal":        "archimate:Goal",
    "principle":   "archimate:Principle",
  },

  SPECIALIZATION_MAP: {
    "ai-app":    "AI Application",
    "ai-model":  "AI Model",
    "assessment":"AI Diagnostic Assessment",
  },

  // Escape XML special characters
  esc(str) {
    return (str || "").replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;");
  },

  generate(model) {
    const esc = this.esc.bind(this);
    const now = new Date().toISOString();
    const modelId = "model-" + Date.now();

    let xml = `<?xml version="1.0" encoding="UTF-8"?>\n`;
    xml += `<archimate:model xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"\n`;
    xml += `    xmlns:archimate="http://www.opengroup.org/xsd/archimate/3.0/"\n`;
    xml += `    name="${esc(model.name || "AI Integration Model")}"\n`;
    xml += `    id="${esc(modelId)}"\n`;
    xml += `    version="3.0">\n\n`;

    // Documentation / description
    if (model.description) {
      xml += `  <!-- ${esc(model.description)} -->\n\n`;
    }
    xml += `  <!-- Generated by AI Integration Architecture Toolkit -->\n`;
    xml += `  <!-- Generated at: ${now} -->\n\n`;

    // ── Elements ─────────────────────────────────────────────────────
    xml += `  <elements>\n\n`;
    for (const el of (model.elements || [])) {
      const xsiType = this.TYPE_MAP[el.type] || "archimate:ApplicationComponent";
      const spec = this.SPECIALIZATION_MAP[el.type];

      xml += `    <element xsi:type="${xsiType}" id="${esc(el.id)}" name="${esc(el.name)}">\n`;

      if (el.description) {
        xml += `      <documentation>${esc(el.description)}</documentation>\n`;
      }

      if (spec) {
        xml += `      <specialization name="${esc(spec)}"/>\n`;
      }

      const props = el.props || {};
      const propKeys = Object.keys(props).filter(k => props[k] && props[k].trim() !== "");
      if (propKeys.length > 0) {
        xml += `      <properties>\n`;
        for (const k of propKeys) {
          xml += `        <property key="${esc(k)}" value="${esc(props[k])}"/>\n`;
        }
        xml += `      </properties>\n`;
      }

      xml += `    </element>\n\n`;
    }
    xml += `  </elements>\n\n`;

    // ── Relationships ─────────────────────────────────────────────────
    xml += `  <relationships>\n\n`;
    for (const rel of (model.relationships || [])) {
      const relType = this.REL_TYPE_MAP[rel.type] || "archimate:AssociationRelationship";
      xml += `    <relationship xsi:type="${relType}" id="${esc(rel.id)}" source="${esc(rel.source)}" target="${esc(rel.target)}"`;
      if (rel.name) xml += ` name="${esc(rel.name)}"`;
      xml += `/>\n`;
    }
    xml += `\n  </relationships>\n\n`;

    // ── Views ─────────────────────────────────────────────────────────
    xml += `  <views>\n    <diagrams>\n\n`;
    xml += `      <view xsi:type="archimate:ArchimateDiagramModel"\n`;
    xml += `          id="view-overview" name="Overview — ${esc(model.name || "AI Integration")}">\n`;
    xml += `        <children>\n`;

    // Auto-layout: place elements in rows by type
    const typeOrder = ["stakeholder","driver","goal","principle","constraint","function","role","actor","process","ai-app","ai-model","assessment"];
    let y = 20;
    for (const t of typeOrder) {
      const els = (model.elements || []).filter(e => e.type === t);
      if (els.length === 0) continue;
      let x = 20;
      for (const el of els) {
        xml += `          <child xsi:type="archimate:DiagramObject" id="vo-${esc(el.id)}" archimateElement="${esc(el.id)}" x="${x}" y="${y}" w="180" h="60"/>\n`;
        x += 200;
        if (x > 1000) { x = 20; y += 80; }
      }
      y += 90;
    }

    xml += `        </children>\n      </view>\n\n    </diagrams>\n  </views>\n\n`;
    xml += `</archimate:model>\n`;
    return xml;
  },

  REL_TYPE_MAP: {
    "used-by":       "archimate:UsedByRelationship",
    "assignment":    "archimate:AssignmentRelationship",
    "composition":   "archimate:CompositionRelationship",
    "aggregation":   "archimate:AggregationRelationship",
    "realization":   "archimate:RealizationRelationship",
    "serving":       "archimate:ServingRelationship",
    "access":        "archimate:AccessRelationship",
    "influence":     "archimate:InfluenceRelationship",
    "triggering":    "archimate:TriggeringRelationship",
    "flow":          "archimate:FlowRelationship",
    "specialization":"archimate:SpecializationRelationship",
    "association":   "archimate:AssociationRelationship",
  },
};
